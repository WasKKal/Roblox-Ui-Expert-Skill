#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""check_api_support.py — 无头运行时的执行器 / 环境 API 支持率审计。

用 references/executor-api-list.txt（373 个真实执行器环境里探测到的全局 API）
生成一段 Luau 探测场景，交给 run_ui.py（lupa 路径）执行，统计运行时真正提供了
多少个名字（含 debug.* / crypt.base64.* / Drawing.new 这类命名空间成员）。

用法：
    python3 scripts/check_api_support.py                 # 人类可读报告
    python3 scripts/check_api_support.py --json          # 机器可读
    python3 scripts/check_api_support.py --details       # 列出缺失项
    python3 scripts/check_api_support.py --luau          # 用真实 luau 路径复测

支持率 = 已提供数 / 清单总数。用于量化「兼容更多真实脚本」的改进幅度。
"""

import argparse
import json
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
LIST = os.path.join(ROOT, "references", "executor-api-list.txt")


def load_names():
    out = []
    for line in open(LIST, encoding="utf-8"):
        line = line.strip()
        if line and not line.startswith("#"):
            out.append(line)
    return list(dict.fromkeys(out))


def lua_quote(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def build_scenario(names):
    arr = ",\n  ".join(lua_quote(n) for n in names)
    return """-- generated by check_api_support.py
local NAMES = {
  %s
}
local G = getfenv(0)
local function resolve(n)
  local cur = G
  for part in string.gmatch(n, "[^%%.]+") do
    if type(cur) ~= "table" then return nil end
    cur = cur[part]
  end
  return cur
end
local ok, missing = 0, {}
for _, n in ipairs(NAMES) do
  local v = resolve(n)
  if v ~= nil then
    ok = ok + 1
  else
    missing[#missing + 1] = n
  end
end
print("APISUPPORT " .. tostring(ok) .. "/" .. tostring(#NAMES))
for i, n in ipairs(missing) do
  print("APIMISS " .. n)
end
check("api support probe completed", ok >= 0)
""" % arr


def run_probe(names, use_luau):
    with tempfile.TemporaryDirectory(prefix="robloxui_api_") as td:
        sc = os.path.join(td, "api_probe.lua")
        open(sc, "w", encoding="utf-8").write(build_scenario(names))
        if use_luau:
            cmd = [sys.executable, os.path.join(HERE, "run_ui_luau.py"),
                   "--scenario", sc, "--out", os.path.join(td, "p.png"),
                   "--style", "none", "--pump-after", "0", "--offline"]
        else:
            cmd = [sys.executable, os.path.join(HERE, "run_ui.py"),
                   "--scenario", sc, "--no-final-snapshot"]
        p = subprocess.run(cmd, capture_output=True, text=True, timeout=180)
        out = p.stdout + p.stderr
    m = re.search(r"APISUPPORT\s+(\d+)/(\d+)", out)
    if not m:
        return {"error": "probe did not run", "raw_tail": out[-1500:]}
    ok, total = int(m.group(1)), int(m.group(2))
    missing = re.findall(r"APIMISS\s+(\S+)", out)
    return {
        "supported": ok,
        "total": total,
        "percent": round(ok * 100.0 / total, 1),
        "missing": missing,
        "backend": "luau" if use_luau else "lupa",
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--details", action="store_true")
    ap.add_argument("--luau", action="store_true")
    args = ap.parse_args()
    names = load_names()
    res = run_probe(names, args.luau)
    if "error" in res:
        print(json.dumps(res, ensure_ascii=False, indent=2) if args.json else res)
        return 1
    if args.json:
        print(json.dumps(res, ensure_ascii=False, indent=2))
        return 0
    print("=== executor API support (%s backend) ===" % res["backend"])
    print("supported : %d / %d" % (res["supported"], res["total"]))
    print("rate      : %.1f%%" % res["percent"])
    print("missing   : %d" % len(res["missing"]))
    if args.details:
        for n in res["missing"]:
            print("   -", n)
    return 0


if __name__ == "__main__":
    sys.exit(main())
